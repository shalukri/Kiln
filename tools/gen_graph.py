#!/usr/bin/env python3
"""Print a random build graph in the kiln file format.

Tasks are put into layers and only depend on tasks from earlier layers, so the graph is
acyclic unless --cycle is given. Example:

    python3 tools/gen_graph.py --nodes 500 --layers 12 --seed 3 > big.kiln
"""
import argparse
import random


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--nodes", type=int, default=200)
    ap.add_argument("--layers", type=int, default=8)
    ap.add_argument("--max-deps", type=int, default=4)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--cycle", action="store_true", help="add one edge that closes a cycle")
    ap.add_argument("--flat-cost", action="store_true", help="give every task cost 10, makes lots of ties")
    ap.add_argument("--no-shuffle", action="store_true", help="keep the lines in layer order")
    args = ap.parse_args()

    if args.nodes < 1 or args.layers < 1 or args.max_deps < 0:
        ap.error("nodes and layers must be at least 1, max-deps at least 0")
    layers = min(args.layers, args.nodes)
    rng = random.Random(args.seed)

    # every layer gets at least one task, the rest are spread randomly
    layer_of = list(range(layers)) + [rng.randrange(layers) for _ in range(args.nodes - layers)]
    layer_of.sort()
    names = ["t%05d" % i for i in range(args.nodes)]
    members = [[] for _ in range(layers)]
    for i, l in enumerate(layer_of):
        members[l].append(i)

    deps = {i: [] for i in range(args.nodes)}
    for i in range(args.nodes):
        l = layer_of[i]
        if l == 0:
            continue
        for _ in range(rng.randint(1, max(1, args.max_deps))):
            # mostly depend on the layer right before, sometimes reach further back
            src = l - 1 if rng.random() < 0.7 else rng.randrange(l)
            deps[i].append(rng.choice(members[src]))
        deps[i] = sorted(set(deps[i]))

    if args.cycle and layers > 1:
        top = rng.choice(members[layers - 1])
        cur = top
        while deps[cur]:                 # walk down to a task with no dependencies
            cur = deps[cur][0]
        deps[cur].append(top)            # the bottom task now depends on the top one

    if args.flat_cost:
        cost = {i: 10 for i in range(args.nodes)}
    else:
        cost = {i: min(5000, int(rng.lognormvariate(4.0, 1.0)) + 1) for i in range(args.nodes)}
    order = list(range(args.nodes))
    if not args.no_shuffle:
        rng.shuffle(order)

    print("# generated by gen_graph.py, nodes=%d layers=%d seed=%d%s" %
          (args.nodes, layers, args.seed, " (contains a cycle)" if args.cycle else ""))
    for i in order:
        print("%s %d : %s" % (names[i], cost[i], " ".join(names[d] for d in deps[i])))


if __name__ == "__main__":
    main()
